-- AGE is left-joined from PIO_COLL.PIO_CUSTOMERS_INFO (the curated
-- customer table, keyed by ID = CUST_INFO_ID) for the Phase 3 LinUCB
-- context vector (docs/phase3_contextual_bandit_rl.md sec 5.2). NULL for
-- synthetic test customers with no real-customer counterpart (expected in
-- dev/test) - null-filled downstream in repository.py, not here.
SELECT
    m.CUST_INFO_ID,
    m.ACCOUNT_STATUS,
    m.TOTAL_DUE,
    m.SMS_SENT_THIS_WEEK,
    m.CALLS_MADE_TODAY,
    m.FULL_LEGAL_NAME,
    m.CUSTOMER_SEGMENT,
    m.NATIONALITY_RESIDENCY,
    m.EMPLOYER_NAME,
    m.VERIFIED_INCOME_JOD,
    m.INCOME_LAST_VERIFIED_DATE,
    m.AML_LAST_SCREENED_DATE,
    m.ACCOUNT_OPEN_DATE,
    m.PRODUCTS_HELD,
    m.PRIMARY_PHONE,
    m.SCORE_DELTA_90D,
    m.COMPOSITE_RISK_SCORE,
    m.DAYS_PAST_DUE,
    DBMS_LOB.SUBSTR(m.CLASSIFICATION_PROBABILITIES, 4000) AS CLASSIFICATION_PROBABILITIES,
    m.PAYMENT_REJECTION_FREQ,
    m.CONTACT_AVOIDANCE_INDEX,
    m.TOTAL_EXPOSURE_JOD,
    m.CURRENT_ARREARS_JOD,
    m.ACCRUED_INTEREST_JOD,
    m.LATE_FEES_JOD,
    m.CALL_RESPONSE_RATE,
    m.FIELD_VISIT_RESPONSE_RATE,
    m.SMS_ESTIMATED_RESPONSE_RATE,
    m.EMAIL_ESTIMATED_RESPONSE_RATE,
    m.LETTER_ESTIMATED_RESPONSE_RATE,
    cust.AGE
FROM BI_DWH.PIO_COLL_AI_NBA_CONTEXT_MART m
LEFT JOIN (
    SELECT ID, AGE,
           ROW_NUMBER() OVER (PARTITION BY ID ORDER BY DAY_DATE DESC) AS RN
    FROM PIO_COLL.PIO_CUSTOMERS_INFO
) cust
    ON  cust.ID = m.CUST_INFO_ID
    AND cust.RN = 1
WHERE m.DAY_DATE    = TO_DATE(:day_date, 'YYYY-MM-DD')
  AND m.INST_CODE   = :inst_code
  AND m.COUNTRY_CODE = :country_code
